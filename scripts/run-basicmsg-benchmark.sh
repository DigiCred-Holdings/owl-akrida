#!/usr/bin/env bash
# Orchestrate local ACA-Py basic-message benchmark runs.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

PROJECT="${COMPOSE_PROJECT_NAME:-owl-benchmark}"
COMPOSE=(docker compose -p "$PROJECT" -f docker-compose.demo.yml -f docker-compose.benchmark.yml --env-file sample.benchmark.env)
RESULTS_ROOT="${RESULTS_ROOT:-$ROOT/results/basicmsg}"
RUNTIME_ENV="$ROOT/.benchmark.runtime.env"
mkdir -p "$RESULTS_ROOT"

usage() {
  cat <<EOF
Usage: $0 <command> [args]

Commands:
  up                 Build/start issuer, dbs, redis, mediator (not the locust service)
  down               Stop the stack (keeps volumes)
  reset              Stop stack and remove volumes
  mediator-invite    Print the mediator invitation URL
  ensure-mediator    Capture mediator invite into .benchmark.runtime.env
  run <name>         Run one benchmark profile into results/basicmsg/<name>
  matrix             Run the original experiment matrix and write SUMMARY.md
  isolate            Run ACA-Py isolation matrix (no mediator/redis; PG vs SQLite; e2e vs admin)

Profiles:
  direct-1x20 / direct-20x1 / mediated-* / direct-20x1-pool50 / direct-20x1-debug
  isolate-pg-e2e / isolate-sqlite-e2e / isolate-pg-admin / isolate-sqlite-admin
  fastpath-pg-admin / fastpath-pg-e2e   (didcomm_fastpath plugin route)
  fastpath-pg-admin-sink[-N]            (pack with real keys, deliver to mock-holder)
EOF
}

compose() {
  local extra=()
  if [[ -f "$RUNTIME_ENV" ]]; then
    extra+=(--env-file "$RUNTIME_ENV")
  fi
  "${COMPOSE[@]}" "${extra[@]}" "$@"
}

write_runtime_env() {
  local wallet_cfg="${ACAPY_WALLET_STORAGE_CONFIG-}"
  local wallet_creds='{"account":"test","password":"test","admin_account":"test","admin_password":"test"}'
  if [[ -n "${ACAPY_WALLET_STORAGE_CREDS-}" ]]; then
    wallet_creds="${ACAPY_WALLET_STORAGE_CREDS}"
  fi
  if [[ "${ACAPY_CLEAR_WALLET_STORAGE_CONFIG:-0}" != "1" && -z "$wallet_cfg" ]]; then
    wallet_cfg='{"url":"issuer-db:5432","max_connections":5}'
  fi
  cat >"$RUNTIME_ENV" <<EOF
# Generated by run-basicmsg-benchmark.sh — do not commit
WITH_MEDIATION=${WITH_MEDIATION:-}
MEDIATION_URL=${MEDIATION_URL:-}
LOCUST_USERS=${LOCUST_USERS:-1}
LOCUST_SPAWN_RATE=${LOCUST_SPAWN_RATE:-1}
CONNECTIONS_PER_AGENT=${CONNECTIONS_PER_AGENT:-1}
TARGET_MESSAGE_COUNT=${TARGET_MESSAGE_COUNT:-10000}
MESSAGE_TO_SEND=${MESSAGE_TO_SEND:-ping}
MEASURE_MODE=${MEASURE_MODE:-e2e}
ACAPY_LOG_LEVEL=${ACAPY_LOG_LEVEL:-info}
ACAPY_ARG_FILE=${ACAPY_ARG_FILE:-issuer-benchmark.yml}
ACAPY_USE_REDIS=${ACAPY_USE_REDIS:-1}
ACAPY_WALLET_STORAGE_CONFIG=${wallet_cfg}
ACAPY_WALLET_STORAGE_CREDS=${wallet_creds}
ISSUER_DOCKERFILE=${ISSUER_DOCKERFILE:-./docker/Dockerfile}
ISSUER_IMAGE_NAME=${ISSUER_IMAGE_NAME:-acapy-cache-redis}
KANON_STORAGE_DATABASE_URL=${KANON_STORAGE_DATABASE_URL:-}
KANON_STORAGE_MASTER_KEY=${KANON_STORAGE_MASTER_KEY:-}
KANON_STORAGE_AUTO_MIGRATE=${KANON_STORAGE_AUTO_MIGRATE:-}
FASTPATH_DELIVER_OVERRIDE=${FASTPATH_DELIVER_OVERRIDE:-}
FASTPATH_PACK_WORKERS=${FASTPATH_PACK_WORKERS:-32}
FASTPATH_CACHE_TTL=${FASTPATH_CACHE_TTL:-30}
FASTPATH_CACHE_MAX=${FASTPATH_CACHE_MAX:-8192}
RUN_NAME=${RUN_NAME:-manual}
EOF
}

cmd_up() {
  compose up -d --build issuer-db redis-host mediator-db mediator issuer
  compose stop load-agent >/dev/null 2>&1 || true
  echo "Waiting for issuer /status/live ..."
  for _ in $(seq 1 90); do
    if curl -sf "http://localhost:8150/status/live" >/dev/null 2>&1; then
      echo "Issuer is live"
      return 0
    fi
    sleep 2
  done
  echo "Issuer failed to become live" >&2
  compose logs --tail=120 issuer >&2 || true
  return 1
}

cmd_down() {
  compose down --remove-orphans
}

cmd_reset() {
  compose down -v --remove-orphans
  rm -f "$RUNTIME_ENV"
}

cmd_mediator_invite() {
  compose logs mediator 2>/dev/null | grep -Eo 'https?://[^ ]+\?c_i=[A-Za-z0-9+/=]+' | tail -n1
}

cmd_ensure_mediator() {
  local invite=""
  for _ in $(seq 1 45); do
    invite="$(cmd_mediator_invite || true)"
    if [[ -n "$invite" ]]; then
      break
    fi
    sleep 2
  done
  if [[ -z "$invite" ]]; then
    echo "Failed to locate mediator invitation" >&2
    compose logs --tail=80 mediator >&2 || true
    return 1
  fi
  invite="${invite//http:\/\/localhost:3000/http://mediator:3000}"
  invite="${invite//http:\/\/host.docker.internal:3000/http://mediator:3000}"
  MEDIATION_URL="$invite"
  export MEDIATION_URL
  echo "MEDIATION_URL=$MEDIATION_URL"
}

profile_env() {
  local name="$1"
  RUN_NAME="$name"
  TARGET_MESSAGE_COUNT="${TARGET_MESSAGE_COUNT_OVERRIDE:-10000}"
  MESSAGE_TO_SEND="${MESSAGE_TO_SEND:-ping}"
  ACAPY_LOG_LEVEL=info
  ACAPY_ARG_FILE=issuer-benchmark.yml
  ACAPY_USE_REDIS=1
  ACAPY_WALLET_STORAGE_CONFIG='{"url":"issuer-db:5432","max_connections":5}'
  ACAPY_CLEAR_WALLET_STORAGE_CONFIG=0
  MEASURE_MODE=e2e
  WITH_MEDIATION=""
  MEDIATION_URL="${MEDIATION_URL:-}"
  LOCUST_SPAWN_RATE=5
  FASTPATH_DELIVER_OVERRIDE=""
  FASTPATH_PACK_WORKERS=32
  FASTPATH_CACHE_TTL="${FASTPATH_CACHE_TTL:-30}"
  FASTPATH_CACHE_MAX="${FASTPATH_CACHE_MAX:-8192}"
  # Storage backend selection (default = stock Askar image). Kanon profiles
  # override these to build/run the Dockerfile.kanon image.
  ISSUER_DOCKERFILE="./docker/Dockerfile"
  ISSUER_IMAGE_NAME="acapy-cache-redis"
  KANON_STORAGE_DATABASE_URL=""
  KANON_STORAGE_MASTER_KEY=""
  KANON_STORAGE_AUTO_MIGRATE=""

  case "$name" in
    direct-1x20|direct-1x20-r2)
      LOCUST_USERS=1
      CONNECTIONS_PER_AGENT=20
      LOCUST_SPAWN_RATE=1
      ;;
    direct-20x1|direct-20x1-r2)
      LOCUST_USERS=20
      CONNECTIONS_PER_AGENT=1
      ;;
    mediated-1x20)
      LOCUST_USERS=1
      CONNECTIONS_PER_AGENT=20
      LOCUST_SPAWN_RATE=1
      WITH_MEDIATION=True
      ;;
    mediated-20x1)
      LOCUST_USERS=20
      CONNECTIONS_PER_AGENT=1
      WITH_MEDIATION=True
      ;;
    direct-20x1-pool50)
      LOCUST_USERS=20
      CONNECTIONS_PER_AGENT=1
      ACAPY_WALLET_STORAGE_CONFIG='{"url":"issuer-db:5432","max_connections":50}'
      ;;
    direct-20x1-debug)
      LOCUST_USERS=20
      CONNECTIONS_PER_AGENT=1
      ACAPY_LOG_LEVEL=debug
      ;;
    isolate-pg-e2e)
      LOCUST_USERS=20
      CONNECTIONS_PER_AGENT=1
      ACAPY_ARG_FILE=issuer-isolated-pg.yml
      ACAPY_USE_REDIS=0
      # Pool sized above concurrency so Postgres is not the artificial limiter.
      ACAPY_WALLET_STORAGE_CONFIG='{"url":"issuer-db:5432","max_connections":30}'
      MEASURE_MODE=e2e
      ;;
    isolate-sqlite-e2e)
      LOCUST_USERS=20
      CONNECTIONS_PER_AGENT=1
      ACAPY_ARG_FILE=issuer-isolated-sqlite.yml
      ACAPY_USE_REDIS=0
      ACAPY_WALLET_STORAGE_CONFIG=
      ACAPY_CLEAR_WALLET_STORAGE_CONFIG=1
      MEASURE_MODE=e2e
      ;;
    isolate-pg-admin)
      LOCUST_USERS=20
      CONNECTIONS_PER_AGENT=1
      ACAPY_ARG_FILE=issuer-isolated-pg.yml
      ACAPY_USE_REDIS=0
      ACAPY_WALLET_STORAGE_CONFIG='{"url":"issuer-db:5432","max_connections":30}'
      MEASURE_MODE=admin_only
      ;;
    isolate-sqlite-admin)
      LOCUST_USERS=20
      CONNECTIONS_PER_AGENT=1
      ACAPY_ARG_FILE=issuer-isolated-sqlite.yml
      ACAPY_USE_REDIS=0
      ACAPY_WALLET_STORAGE_CONFIG=
      ACAPY_CLEAR_WALLET_STORAGE_CONFIG=1
      MEASURE_MODE=admin_only
      ;;
    fastpath-pg-admin-sink|fastpath-pg-admin-sink-*)
      # Real Credo connections for keys; deliver to mock-holder (no unpack).
      LOCUST_USERS="${LOCUST_USERS_OVERRIDE:-20}"
      CONNECTIONS_PER_AGENT=1
      ACAPY_ARG_FILE=issuer-isolated-pg-fastpath.yml
      ACAPY_USE_REDIS=0
      ACAPY_WALLET_STORAGE_CONFIG='{"url":"issuer-db:5432","max_connections":30}'
      MEASURE_MODE=fastpath_admin
      FASTPATH_DELIVER_OVERRIDE=http://mock-holder:8090/
      FASTPATH_PACK_WORKERS="${FASTPATH_PACK_WORKERS:-32}"
      ;;
    fastpath-pg-admin|fastpath-pg-admin-*)
      LOCUST_USERS="${LOCUST_USERS_OVERRIDE:-20}"
      CONNECTIONS_PER_AGENT=1
      ACAPY_ARG_FILE=issuer-isolated-pg-fastpath.yml
      ACAPY_USE_REDIS=0
      ACAPY_WALLET_STORAGE_CONFIG='{"url":"issuer-db:5432","max_connections":30}'
      MEASURE_MODE=fastpath_admin
      ;;
    fastpath-pg-e2e|fastpath-pg-e2e-*)
      LOCUST_USERS="${LOCUST_USERS_OVERRIDE:-20}"
      CONNECTIONS_PER_AGENT=1
      ACAPY_ARG_FILE=issuer-isolated-pg-fastpath.yml
      ACAPY_USE_REDIS=0
      ACAPY_WALLET_STORAGE_CONFIG='{"url":"issuer-db:5432","max_connections":30}'
      MEASURE_MODE=fastpath
      ;;
    kanon-fastpath-admin-sink|kanon-fastpath-admin-sink-*)
      # Kanon storage backend; real Credo connections for keys; deliver to
      # mock-holder (isolates the issuer's own ceiling). Compare vs
      # fastpath-pg-admin-sink (stock Askar).
      LOCUST_USERS="${LOCUST_USERS_OVERRIDE:-20}"
      CONNECTIONS_PER_AGENT=1
      ACAPY_ARG_FILE=issuer-isolated-kanon-fastpath.yml
      ACAPY_USE_REDIS=0
      ACAPY_WALLET_STORAGE_CONFIG=
      ACAPY_CLEAR_WALLET_STORAGE_CONFIG=1
      MEASURE_MODE=fastpath_admin
      FASTPATH_DELIVER_OVERRIDE=http://mock-holder:8090/
      FASTPATH_PACK_WORKERS="${FASTPATH_PACK_WORKERS:-32}"
      ISSUER_DOCKERFILE="./docker/Dockerfile.kanon"
      ISSUER_IMAGE_NAME="acapy-kanon-benchmark"
      KANON_STORAGE_DATABASE_URL="postgresql+asyncpg://test:test@issuer-db:5432/test"
      KANON_STORAGE_MASTER_KEY="0123456789abcdef0123456789abcdef"
      KANON_STORAGE_AUTO_MIGRATE=true
      ;;
    kanon-fastpath-e2e|kanon-fastpath-e2e-*)
      # Kanon storage backend; real Credo holders end-to-end. Compare vs
      # fastpath-pg-e2e (stock Askar).
      LOCUST_USERS="${LOCUST_USERS_OVERRIDE:-20}"
      CONNECTIONS_PER_AGENT=1
      ACAPY_ARG_FILE=issuer-isolated-kanon-fastpath.yml
      ACAPY_USE_REDIS=0
      ACAPY_WALLET_STORAGE_CONFIG=
      ACAPY_CLEAR_WALLET_STORAGE_CONFIG=1
      MEASURE_MODE=fastpath
      ISSUER_DOCKERFILE="./docker/Dockerfile.kanon"
      ISSUER_IMAGE_NAME="acapy-kanon-benchmark"
      KANON_STORAGE_DATABASE_URL="postgresql+asyncpg://test:test@issuer-db:5432/test"
      KANON_STORAGE_MASTER_KEY="0123456789abcdef0123456789abcdef"
      KANON_STORAGE_AUTO_MIGRATE=true
      ;;
    *)
      echo "Unknown profile: $name" >&2
      return 1
      ;;
  esac

  export RUN_NAME LOCUST_USERS LOCUST_SPAWN_RATE CONNECTIONS_PER_AGENT \
    TARGET_MESSAGE_COUNT MESSAGE_TO_SEND ACAPY_LOG_LEVEL \
    ACAPY_WALLET_STORAGE_CONFIG ACAPY_CLEAR_WALLET_STORAGE_CONFIG \
    ACAPY_ARG_FILE ACAPY_USE_REDIS MEASURE_MODE \
    WITH_MEDIATION MEDIATION_URL \
    FASTPATH_DELIVER_OVERRIDE FASTPATH_PACK_WORKERS \
    ISSUER_DOCKERFILE ISSUER_IMAGE_NAME \
    KANON_STORAGE_DATABASE_URL KANON_STORAGE_MASTER_KEY KANON_STORAGE_AUTO_MIGRATE
}

wait_issuer() {
  for _ in $(seq 1 90); do
    if curl -sf "http://localhost:8150/status/live" >/dev/null 2>&1; then
      return 0
    fi
    sleep 2
  done
  return 1
}

cmd_run() {
  local name="${1:?profile name required}"
  local out="$RESULTS_ROOT/$name"
  rm -rf "$out"
  mkdir -p "$out"

  profile_env "$name"

  if [[ -n "$WITH_MEDIATION" ]]; then
    cmd_ensure_mediator
    local saved_invite="$MEDIATION_URL"
    profile_env "$name"
    MEDIATION_URL="$saved_invite"
    export MEDIATION_URL
  else
    MEDIATION_URL=""
    export MEDIATION_URL
  fi

  write_runtime_env

  compose up -d --build --force-recreate issuer mock-holder
  compose stop load-agent >/dev/null 2>&1 || true
  echo "Waiting for issuer after recreate..."
  if ! wait_issuer; then
    echo "Issuer not live" >&2
    compose logs --tail=160 issuer | tee "$out/issuer-failed.log" >&2
    return 1
  fi
  if [[ -n "${FASTPATH_DELIVER_OVERRIDE:-}" ]]; then
    echo "Waiting for mock-holder..."
    for _ in $(seq 1 30); do
      if curl -sf "http://localhost:8090/health" >/dev/null 2>&1; then
        curl -sf -X DELETE "http://localhost:8090/stats" >/dev/null 2>&1 || true
        break
      fi
      sleep 1
    done
  fi

  {
    echo "run_name=$name"
    echo "started=$(date -Is)"
    echo "commit=$(git rev-parse HEAD)"
    echo "branch=$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo detached)"
    echo "host_cpus=$(nproc)"
    echo "host_mem_kb=$(awk '/MemTotal/ {print $2}' /proc/meminfo)"
    echo "docker=$(docker version --format '{{.Server.Version}}')"
    echo "users=$LOCUST_USERS"
    echo "connections_per_agent=$CONNECTIONS_PER_AGENT"
    echo "target=$TARGET_MESSAGE_COUNT"
    echo "mediation=${WITH_MEDIATION:-false}"
    echo "mediation_url=${MEDIATION_URL:-}"
    echo "measure_mode=$MEASURE_MODE"
    echo "acapy_arg_file=$ACAPY_ARG_FILE"
    echo "acapy_use_redis=$ACAPY_USE_REDIS"
    echo "acapy_log_level=$ACAPY_LOG_LEVEL"
    echo "wallet_storage_config=${ACAPY_WALLET_STORAGE_CONFIG:-sqlite-default}"
    echo "issuer_dockerfile=${ISSUER_DOCKERFILE:-./docker/Dockerfile}"
    echo "storage_backend=$([[ -n "${KANON_STORAGE_DATABASE_URL:-}" ]] && echo kanon || echo askar)"
    echo "kanon_database_url=${KANON_STORAGE_DATABASE_URL:-}"
    echo "fastpath_deliver_override=${FASTPATH_DELIVER_OVERRIDE:-}"
    echo "fastpath_pack_workers=${FASTPATH_PACK_WORKERS:-}"
    echo "fastpath_cache_ttl=${FASTPATH_CACHE_TTL:-}"
    echo "fastpath_cache_max=${FASTPATH_CACHE_MAX:-}"
    echo "message_to_send=$MESSAGE_TO_SEND"
    echo "payload_bytes=$(printf '%s' "$MESSAGE_TO_SEND" | wc -c)"
    echo "issuer_image=$(docker compose -p "$PROJECT" images issuer 2>/dev/null | awk 'NR==2{print $2":"$3}')"
  } | tee "$out/run-meta.txt"

  bash "$ROOT/scripts/collect-stats.sh" "$out" 1800 &
  local collector_pid=$!

  set +e
  compose run --rm --no-deps --use-aliases \
    -e LOCUST_USERS \
    -e CONNECTIONS_PER_AGENT \
    -e TARGET_MESSAGE_COUNT \
    -e "WITH_MEDIATION=${WITH_MEDIATION}" \
    -e "MEDIATION_URL=${MEDIATION_URL}" \
    -e "MEASURE_MODE=${MEASURE_MODE}" \
    -e MESSAGE_TO_SEND \
    -e AGENT_IP=load-agent \
    -e LEDGER=none \
    -e LOCUST_MIN_WAIT=0 \
    -e LOCUST_MAX_WAIT=0 \
    load-agent \
    pdm run locust -f locust-files/locustBasicMsgBenchmark.py \
      --headless \
      -u "$LOCUST_USERS" \
      -r "$LOCUST_SPAWN_RATE" \
      -H http://localhost \
      --csv "/load-agent/results/basicmsg/$name/locust" \
      --html "/load-agent/results/basicmsg/$name/report.html" \
      --only-summary 2>&1 | tee "$out/locust.log"
  local rc=${PIPESTATUS[0]}
  set -e

  kill "$collector_pid" 2>/dev/null || true
  wait "$collector_pid" 2>/dev/null || true

  compose logs --tail=250 issuer >"$out/issuer.log" 2>&1 || true
  compose logs --tail=250 mediator >"$out/mediator.log" 2>&1 || true

  # Capture fastpath per-stage timing stats when the plugin route is active.
  if [[ "$MEASURE_MODE" == fastpath* ]]; then
    curl -sf "http://localhost:8150/didcomm-fastpath/stats" \
      | python3 -m json.tool >"$out/fastpath-stats.json" 2>/dev/null || true
  fi
  if [[ -n "${FASTPATH_DELIVER_OVERRIDE:-}" ]]; then
    curl -sf "http://localhost:8090/stats" \
      | python3 -m json.tool >"$out/mock-holder-stats.json" 2>/dev/null || true
  fi

  local steady
  steady="$(grep -E '^\[benchmark\] finished' "$out/locust.log" | tail -n1 || true)"
  if [[ -n "$steady" ]]; then
    echo "benchmark_line=$steady" | tee -a "$out/run-meta.txt"
    echo "$steady" | sed -E 's/.*steady_state_seconds=([0-9.]+) steady_state_rps=([0-9.]+)/steady_state_seconds=\1\nsteady_state_rps=\2/' | tee -a "$out/run-meta.txt"
  fi

  echo "finished=$(date -Is) exit=$rc" | tee -a "$out/run-meta.txt"
  return "$rc"
}

run_profile_list() {
  local failed=0
  for p in "$@"; do
    echo "===== Running profile $p ====="
    if ! cmd_run "$p"; then
      echo "Profile $p failed (continuing)" >&2
      failed=1
    fi
  done
  python3 "$ROOT/scripts/summarize-basicmsg-results.py" "$RESULTS_ROOT" | tee "$RESULTS_ROOT/SUMMARY.md"
  return "$failed"
}

cmd_matrix() {
  cmd_up
  run_profile_list \
    direct-1x20 \
    direct-20x1 \
    direct-1x20-r2 \
    direct-20x1-r2 \
    mediated-1x20 \
    mediated-20x1 \
    direct-20x1-pool50 \
    direct-20x1-debug
}

cmd_isolate() {
  # Shorter default target for faster concurrency iteration; override with TARGET_MESSAGE_COUNT_OVERRIDE.
  export TARGET_MESSAGE_COUNT_OVERRIDE="${TARGET_MESSAGE_COUNT_OVERRIDE:-2000}"
  # Only need issuer (+ db for PG variant); keep redis/mediator stopped to reduce noise.
  compose up -d --build issuer-db
  compose stop redis-host mediator mediator-db >/dev/null 2>&1 || true
  run_profile_list \
    isolate-pg-e2e \
    isolate-sqlite-e2e \
    isolate-pg-admin \
    isolate-sqlite-admin
  python3 - <<'PY' | tee "$RESULTS_ROOT/ISOLATION.md"
from pathlib import Path
root = Path("results/basicmsg")
rows = []
for name in ["isolate-pg-e2e", "isolate-sqlite-e2e", "isolate-pg-admin", "isolate-sqlite-admin", "direct-20x1"]:
    meta = root / name / "run-meta.txt"
    if not meta.exists():
        continue
    d = {}
    for line in meta.read_text().splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            d[k.strip()] = v.strip()
    rows.append((name, d.get("steady_state_rps", "n/a"), d.get("measure_mode", ""), d.get("wallet_storage_config", ""), d.get("acapy_use_redis", "")))
print("# ACA-Py Isolation Results")
print()
print("| Profile | Steady RPS | Measure | Storage | Redis |")
print("|---|---:|---|---|---|")
for name, rps, mode, storage, redis in rows:
    storage = "sqlite" if "sqlite" in storage or storage == "sqlite-default" else "postgres"
    print(f"| {name} | {rps} | {mode or 'e2e'} | {storage} | {redis or 'n/a'} |")
print()
print("Interpretation: if SQLite ≈ Postgres, storage is not the ceiling. If admin_only ≫ e2e, holder/receipt path dominates the measured latency. If both stay near ~50 RPS with issuer CPU ~1.5 cores, ACA-Py processing itself is the limiter.")
PY
}

main() {
  local cmd="${1:-}"
  shift || true
  case "$cmd" in
    up) cmd_up "$@" ;;
    down) cmd_down "$@" ;;
    reset) cmd_reset "$@" ;;
    mediator-invite) cmd_mediator_invite "$@" ;;
    ensure-mediator) cmd_ensure_mediator "$@" ;;
    run) cmd_run "$@" ;;
    matrix) cmd_matrix "$@" ;;
    isolate) cmd_isolate "$@" ;;
    -h|--help|help|"") usage ;;
    *) echo "Unknown command: $cmd" >&2; usage; return 1 ;;
  esac
}

main "$@"
